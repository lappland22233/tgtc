import type { QueryRunner } from 'typeorm';

export async function createBotInboundQueue(runner: QueryRunner, sqlite: boolean): Promise<void> {
  const timestamp = sqlite ? 'datetime' : 'timestamptz';
  const sequence = sqlite ? 'integer primary key autoincrement' : 'integer generated by default as identity primary key';
  await runner.query(`CREATE TABLE IF NOT EXISTS "telegram_bot_inbound_tasks" (
    "sequence" ${sequence}, "id" varchar(36) NOT NULL,
    "receiverBotId" varchar(32) NOT NULL, "sourceAccountId" varchar(64),
    "telegramUserId" varchar(32) NOT NULL, "telegramUsername" varchar(64), "telegramDisplayName" varchar(128),
    "chatId" varchar(32) NOT NULL, "messageId" varchar(32) NOT NULL, "telegramFileId" varchar(512) NOT NULL,
    "fileUniqueId" varchar(128), "fileName" varchar(255), "mimeType" varchar(128), "fileSize" bigint,
    "status" varchar(16) NOT NULL, "waitingMsgId" integer, "noticeStatus" varchar(16), "noticePosition" integer,
    "nextNoticeAt" ${timestamp}, "noticeLeaseUntil" ${timestamp}, "availableAt" ${timestamp}, "botCooldownUntil" ${timestamp}, "failureReason" varchar(255),
    "usageDate" varchar(10) NOT NULL, "quotaConsumed" boolean NOT NULL, "quotaUsed" integer NOT NULL,
    "leaseToken" varchar(36), "leaseExpiresAt" ${timestamp}, "grantId" varchar(36),
    "createdAt" ${timestamp} NOT NULL, "updatedAt" ${timestamp} NOT NULL, "startedAt" ${timestamp}, "finishedAt" ${timestamp}
  )`);
  await runner.query('CREATE UNIQUE INDEX IF NOT EXISTS "uq_bot_inbound_id" ON "telegram_bot_inbound_tasks" ("id")');
  await runner.query('CREATE UNIQUE INDEX IF NOT EXISTS "uq_bot_inbound_message" ON "telegram_bot_inbound_tasks" ("receiverBotId", "telegramUserId", "chatId", "messageId")');
  await runner.query(`CREATE UNIQUE INDEX IF NOT EXISTS "uq_bot_inbound_running" ON "telegram_bot_inbound_tasks" ("receiverBotId") WHERE "leaseToken" IS NOT NULL`);
  await runner.query('CREATE INDEX IF NOT EXISTS "idx_bot_inbound_fifo" ON "telegram_bot_inbound_tasks" ("receiverBotId", "status", "sequence")');
  await runner.query('CREATE INDEX IF NOT EXISTS "idx_bot_inbound_cooldown" ON "telegram_bot_inbound_tasks" ("receiverBotId", "botCooldownUntil") WHERE "botCooldownUntil" IS NOT NULL');
  await runner.query('CREATE INDEX IF NOT EXISTS "idx_bot_inbound_notice_lease" ON "telegram_bot_inbound_tasks" ("receiverBotId", "noticeLeaseUntil") WHERE "noticeLeaseUntil" IS NOT NULL');
  await runner.query(`CREATE INDEX IF NOT EXISTS "idx_bot_inbound_terminal_notice" ON "telegram_bot_inbound_tasks" ("receiverBotId", "sequence")
    WHERE "status" IN ('completed','failed','cancelled') AND ("noticeStatus" IS NULL OR "noticeStatus" <> "status")`);
  await runner.query('CREATE INDEX IF NOT EXISTS "idx_bot_inbound_user" ON "telegram_bot_inbound_tasks" ("telegramUserId", "sequence")');
  await runner.query(`CREATE TABLE IF NOT EXISTS "telegram_bot_user_bans" (
    "telegramUserId" varchar(32) NOT NULL PRIMARY KEY, "reason" varchar(500) NOT NULL,
    "bannedBy" varchar(64) NOT NULL, "bannedAt" ${timestamp} NOT NULL DEFAULT CURRENT_TIMESTAMP
  )`);
}
